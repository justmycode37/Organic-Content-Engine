import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const policies = {};
for (const [key, file] of [['FORMAT_RESEARCH', 'format-research'], ['CONTENT_DRAFTING', 'content-drafting'], ['VIDEO_PRODUCTION', 'video-production'], ['ANIMATION_REELS', 'animation-reels']]) {
  policies[key] = await readFile(new URL(`docs/content-engine/${file}.md`, root), 'utf8');
}
const output = '// Generated by scripts/sync-content-policies.mjs; edit docs/content-engine/*.md instead.\n'
  + Object.entries(policies).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};\n`).join('');
for (const file of ['server/src/generation/content-policies.ts', 'chatgpt-site/worker/generation/content-policies.ts']) {
  const url = new URL(file, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== output) throw new Error(`Stale policies: ${file}. Run node scripts/sync-content-policies.mjs`);
  } else await writeFile(url, output);
}
