import assert from 'node:assert/strict';
import test from 'node:test';
import {VideoPublisher,captionDisclosesSynthetic,nativeAiDisclosure} from './video.ts';

const json=(value,status=200,headers={})=>new Response(JSON.stringify(value),{status,headers:{'content-type':'application/json',...headers}});
const stream=()=>new ReadableStream({start(controller){controller.close();}});

function makePublisher(platform,network){
 const db={prepare:()=>({bind:()=>({first:async()=>null,run:async()=>({})})})};
 const social={env:{INSTAGRAM_API_VERSION:'v25.0'},token:async()=>({account:{account_id:'account-1',name:'owner'},access:'test-token'}),creator:async()=>({privacy_level_options:['PUBLIC_TO_EVERYONE'],comment_disabled:false,duet_disabled:false,stitch_disabled:false,max_video_post_duration_sec:600,creator_username:'owner'})};
 const materials={get:async()=>({id:'media-1',mime:'video/mp4',size:4}),read:async()=>({stream:stream()})};
 return new VideoPublisher(db,social,materials,network);
}

const baseRequest=(platform,overrides={})=>({platform,text:'AI-generated narration; reporting and sources by PATCH NOTES.',mediaUrls:['storage:media-1'],options:{accountId:'account-1',synthetic:true,privacy:'PUBLIC_TO_EVERYONE',consent:true,duration:2,title:'Patch note'},idempotencyKey:`${platform}-test`,...overrides});

test('Instagram Graph media creation sets is_ai_generated from post metadata',async()=>{
 let createBody;
 const publisher=makePublisher('instagram',async(url,init={})=>{
  if(String(url).endsWith('/media')){createBody=init.body;return json({id:'container-1',uri:'https://rupload.facebook.com/ig-api-upload/test'});}
  return new Response(null,{status:200});
 });
 await publisher.publish('instagram',baseRequest('instagram'));
 assert.equal(new URLSearchParams(createBody).get('is_ai_generated'),'true');
 assert.equal(new URLSearchParams(createBody).get('caption'),baseRequest('instagram').text);
});

test('TikTok Direct Post sets post_info.is_aigc from post metadata',async()=>{
 let requestBody;
 const publisher=makePublisher('tiktok',async(url,init={})=>{
  if(String(url).includes('/video/init/')){requestBody=JSON.parse(init.body);return json({data:{publish_id:'publish-1',upload_url:'https://upload.tiktokapis.com/test'}});}
  return new Response(null,{status:200});
 });
 await publisher.publish('tiktok',baseRequest('tiktok'));
 assert.equal(requestBody.post_info.is_aigc,true);
});

test('YouTube resumable insert sets status.containsSyntheticMedia from post metadata',async()=>{
 let requestBody;
 let calls=0;
 const publisher=makePublisher('youtube',async(_url,init={})=>{
  calls++;
  if(calls===1){requestBody=JSON.parse(init.body);return new Response(null,{status:200,headers:{location:'https://www.googleapis.com/upload/youtube/v3/videos/session'}});}
  return json({id:'youtube-video-1'});
 });
 await publisher.publish('youtube',baseRequest('youtube',{options:{accountId:'account-1',synthetic:true,privacy:'public',title:'Patch note'}}));
 assert.equal(requestBody.status.containsSyntheticMedia,true);
});

test('synthetic videos fail closed without a caption disclosure or verified field',async()=>{
 const publisher=makePublisher('instagram',async()=>{throw new Error('network must not be called');});
 await assert.rejects(()=>publisher.publish('instagram',baseRequest('instagram',{text:'New release video'})),error=>error.code==='ai_disclosure_required');
 await assert.rejects(()=>publisher.publish('instagram',baseRequest('instagram',{options:{accountId:'account-1',synthetic:false}})),error=>error.code==='ai_metadata_mismatch');
 await assert.rejects(()=>publisher.publish('bluesky',baseRequest('bluesky')),error=>error.code==='ai_disclosure_unsupported');
 assert.equal(nativeAiDisclosure('bluesky',true),null);
 assert.equal(captionDisclosesSynthetic('AI-generated narration for this explainer.'),true);
 assert.equal(captionDisclosesSynthetic('Maybe generated by a clever editor.'),false);
});
