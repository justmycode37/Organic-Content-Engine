const KERN: Record<string, number> = {
  AV: -1, AW: -1, AY: -1, LT: -1, LY: -1, TA: -1, TO: -1, TR: -1,
  VA: -1, WA: -1, YA: -1, YO: -1, RA: -1, LA: -1, '11': -1,
};

export type PixelFace = 'heavy';
export interface PixelLabelOptions { color?: string; face?: PixelFace }
export interface PixelMeasure { cols: number; rows: number; w: number; h: number }
const cache = new Map<string, Sprite>();

function glyphFor(char: string): readonly string[] { return HEAVY[char] ?? HEAVY['?']!; }
function glyphWidth(glyph: readonly string[]): number { return Math.max(0, ...glyph.map(row => row.length)); }
function layout(text: string) {
  const chars = [...String(text ?? '').toUpperCase()];
  const starts: number[] = [];
  let x = 0, previous = '';
  for (const char of chars) {
    const glyph = glyphFor(char);
    if (previous) x += KERN[previous + char] ?? 0;
    starts.push(x);
    x += glyphWidth(glyph) + (char === ' ' ? 2 : 1);
    previous = char;
  }
  if (chars.length) x -= 1;
  return { chars, starts, cols: Math.max(0, x), rows: 9 };
}

/** Return text bounds in art pixels (`w`/`h` are device pixels at ART = 6). */
export function measure(text: string, _options: PixelLabelOptions = {}): PixelMeasure {
  const result = layout(text);
  return { cols: result.cols, rows: result.rows, w: result.cols * ART, h: result.rows * ART };
}

/** Rasterise a label into an existing art-grid canvas and return its art-pixel bounds. */
export function paintPixelText(grid: Grid, text: string, x: number, y: number, color: string = PAL.ink, _face: PixelFace = 'heavy'): PixelMeasure {
  const result = layout(text);
  result.chars.forEach((char, index) => {
    const glyph = glyphFor(char), gx = x + result.starts[index]!;
    glyph.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') grid.set(gx + rx, y + ry, color);
    });
  });
  return { cols: result.cols, rows: result.rows, w: result.cols * ART, h: result.rows * ART };
}

/** Build or fetch a cached 9-art-pixel-high pixel wordmark sprite. */
export function pixelLabel(text: string, options: PixelLabelOptions = {}): Sprite {
  const color = options.color ?? PAL.ink, face = options.face ?? 'heavy';
  const layoutResult = layout(text), cols = Math.max(1, layoutResult.cols), rows = layoutResult.rows;
  const key = `pixel-label:${face}:${color}:${String(text ?? '').toUpperCase()}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const grid = new Grid(cols, rows);
  paintPixelText(grid, text, 0, 0, color, face);
  const sprite = grid.sprite(key);
  cache.set(key, sprite);
  return sprite;
}
