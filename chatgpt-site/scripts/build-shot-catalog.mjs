#!/usr/bin/env node
// Regenerates src/motion/shots/catalog.ts (pure data, worker-safe) from the shot files:
// every shot's name + describe line, the actor ids and the item ids a spec may use.
// Run after adding or changing a shot: `node scripts/build-shot-catalog.mjs`.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'motion');
const dir = join(root, 'shots');
const skip = new Set(['index.ts', 'catalog.ts', 'common.ts']);
const entries = [];
for (const file of (await readdir(dir)).filter(f => f.endsWith('.ts') && !skip.has(f) && !f.startsWith('demo-')).sort()) {
  const source = await readFile(join(dir, file), 'utf8');
  const name = source.match(/\bname:\s*'([a-z0-9-]+)'/)?.[1];
  const describe = source.match(/\bdescribe:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`)/);
  if (!name || !describe) throw new Error(`${file}: missing name or describe`);
  const text = (describe[1] ?? describe[2] ?? describe[3]).replace(/\\(['"`])/g, '$1').replace(/\s+/g, ' ').trim();
  entries.push({ name, describe: text });
}
const common = await readFile(join(dir, 'common.ts'), 'utf8');
const itemsBlock = common.slice(common.indexOf('export const ITEMS = {'), common.indexOf('} satisfies Record<string, Item>'));
const items = [...itemsBlock.matchAll(/(?:^|[\s,{])([a-zA-Z][a-zA-Z0-9]*):\s*I\(/g)].map(m => m[1]);
const people = await readFile(join(root, 'props', 'people.ts'), 'utf8');
const rolesBlock = people.slice(people.indexOf('export const ROLE_ALIASES = {'), people.indexOf('} as const satisfies'));
const roles = [...rolesBlock.matchAll(/^\s*([a-z0-9]+):\s*\{\s*species:\s*'([a-z0-9]+)'/gm)].map(m => ({ role: m[1], species: m[2] }));
const cast = [...people.matchAll(/\{ id: '([a-z0-9]+)', looks: '([^']+)'/g)].map(m => ({ id: m[1], looks: m[2] }));
if (!items.length || !roles.length || !cast.length) throw new Error('could not read items / roles / cast');

const core = await readFile(join(root, 'core.ts'), 'utf8');
const transitions = core.match(/export const TRANSITIONS\s*=\s*(\[[^\]]+\])/)?.[1];
if (!transitions) throw new Error('could not read TRANSITIONS');

const out = `// GENERATED by scripts/build-shot-catalog.mjs — do not edit by hand.
// Pure-data catalog of the general shot library, safe to import from the worker (no canvas code).
export interface ShotCatalogEntry { name: string; describe: string }
export const SHOT_CATALOG: readonly ShotCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
export const SHOT_NAMES = SHOT_CATALOG.map(entry => entry.name);
/** Props a spec may name in item-type params. */
export const SHOT_ITEMS = ${JSON.stringify(items)} as const;
/** Cast: 'hedgy' (the mascot), role presets and species. */
export const SHOT_ROLES = ${JSON.stringify(roles)} as const;
export const SHOT_CAST = ${JSON.stringify(cast)} as const;
export const SHOT_ACTORS = ['hedgy', ...SHOT_ROLES.map(r => r.role), ...SHOT_CAST.map(c => c.id).filter(id => id !== 'hedgy')];
/** Transitions that stay clean on the flat stage. */
export const CLEAN_TRANSITIONS = ['cut', 'push', 'match', 'iris'] as const;
export const describeShotCatalog = () => [
  'SHOTS (type "shot"; params are optional and have sensible defaults; sync words drive the events in order):',
  ...SHOT_CATALOG.map(entry => \`- \${entry.name}: \${entry.describe}\`),
  \`ITEMS: \${SHOT_ITEMS.join(', ')}\`,
  \`ACTORS: hedgy (the brown hedgehog mascot); roles \${SHOT_ROLES.map(r => \`\${r.role} (\${r.species})\`).join(', ')}; species \${SHOT_CAST.filter(c => c.id !== 'hedgy').map(c => \`\${c.id} (\${c.looks})\`).join(', ')}\`,
  \`TRANSITIONS: \${CLEAN_TRANSITIONS.join(', ')} (push takes transitionDir left|right|up|down)\`,
].join('\\n');
/** Mirror of core.ts TRANSITIONS for worker code that cannot import canvas types (kept equal by motion.test.mjs). */
export const SHOT_TRANSITIONS = ${transitions} as const;
`;
await writeFile(join(dir, 'catalog.ts'), out);
console.log(`catalog: ${entries.length} shots, ${items.length} items, ${roles.length} roles, ${cast.length} cast`);
